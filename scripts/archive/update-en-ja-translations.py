modules = ['menu-config', 'i18n-admin']

for module_name in modules:
    for locale, translations in [('en-US', en_translations), ('ja-JP', ja_translations)]:
        file_path = os.path.join(src_dir, module_name, 'locales', locale, f'{module_name}.json')
        if not os.path.exists(file_path):
            continue
        
        with open(file_path, 'r', encoding='utf-8') as fp:
            data = json.load(fp)
        
        new_data = {}
        for key, value in data.items():
            if key in translations:
                new_data[key] = translations[key]
            else:
                new_data[key] = value
        
        with open(file_path, 'w', encoding='utf-8') as fp:
            json.dump(new_data, fp, ensure_ascii=False, indent=2)
        
        print(f'Updated: {file_path}')

